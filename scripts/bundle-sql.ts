// Writes db/supabase/all.sql: every migration in order plus row-level security, ready to paste
// into the Supabase SQL editor (or apply through Bolt's Supabase connection) in one step.
import fs from 'node:fs';
import path from 'node:path';

const dir = 'db/migrations';
const parts = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort().map((f) => `-- ===== ${f} =====\n${fs.readFileSync(path.join(dir, f), 'utf8').trim()}\n`);
// Records the migrations as applied so `npm run db:migrate` later skips them.
const names = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const out = `-- honeydoo database, generated by npm run db:bundle. Run once on an empty Supabase project.
begin;
${parts.join('\n')}
-- ===== row-level security =====
${fs.readFileSync('db/supabase/rls.sql', 'utf8').trim()}

create table if not exists schema_migrations (name text primary key, applied_at timestamptz not null default now());
alter table schema_migrations enable row level security;
insert into schema_migrations(name) values ${names.map((n) => `('${n}')`).join(', ')} on conflict do nothing;
commit;
`;
fs.writeFileSync('db/supabase/all.sql', out);
console.log(`wrote db/supabase/all.sql (${names.length} migrations + RLS)`);
