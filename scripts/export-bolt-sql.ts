// Writes the files Bolt (and any Supabase project) uses to build the database:
//   supabase/migrations/20261014000000_honeydoo_schema.sql  every table, index and security rule
//   supabase/seed.sql                                       optional demo shops (fictional, is_demo = true)
// Regenerate after schema or seed changes: npm run db:bolt
import fs from 'node:fs';
import { createPglite, runMigrations } from '../src/lib/db';
import { seedDemo } from '../db/seed/seed';

(async () => {
  // Schema: the same bundle as db/supabase/all.sql, without its own transaction wrapper (migration runners add one).
  const bundle = fs.readFileSync('db/supabase/all.sql', 'utf8').replace(/^begin;\n/m, '').replace(/^commit;\n?/m, '');
  fs.mkdirSync('supabase/migrations', { recursive: true });
  fs.writeFileSync('supabase/migrations/20261014000000_honeydoo_schema.sql',
    `-- honeydoo schema. Generated by npm run db:bolt from db/migrations. Do not edit; add a new migration instead.\n${bundle}`);

  // Demo data: seed an in-memory database, then dump it table by table in foreign-key order.
  const db = await createPglite();
  await runMigrations(db);
  await seedDemo(db);
  const tables = (await db.query<{ t: string }>(`select tablename t from pg_tables where schemaname = 'public' and tablename <> 'schema_migrations'`)).rows.map((r) => r.t);
  const deps = (await db.query<{ child: string; parent: string }>(
    `select c.conrelid::regclass::text child, c.confrelid::regclass::text parent from pg_constraint c where c.contype = 'f' and c.connamespace = 'public'::regnamespace`)).rows;
  const ordered: string[] = []; const seen = new Set<string>();
  const visit = (t: string) => { if (seen.has(t)) return; seen.add(t); deps.filter((d) => d.child === t && d.parent !== t).forEach((d) => visit(d.parent)); ordered.push(t); };
  tables.sort().forEach(visit);

  let sql = `-- honeydoo demo data: 9 fictional Lakewood shops (is_demo = true). Optional; never load into a launch database.
-- Safe to run more than once. Remove all demo data with: delete from merchants where is_demo;
begin;
`;
  let rows = 0;
  for (const t of ordered) {
    const r = await db.query<{ j: unknown[] | null }>(`select json_agg(x) j from ${t} x`);
    const data = r.rows[0].j;
    if (!data?.length) continue;
    rows += data.length;
    const json = JSON.stringify(data).replace(/'/g, "''");
    sql += `insert into ${t} select * from json_populate_recordset(null::${t}, '${json}') on conflict do nothing;\n`;
  }
  sql += 'commit;\n';
  fs.writeFileSync('supabase/seed.sql', sql);
  console.log(`wrote supabase/migrations (schema) and supabase/seed.sql (${rows} rows)`);
  await db.close();
})().catch((e) => { console.error(e); process.exit(1); });
